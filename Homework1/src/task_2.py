positive = 4
negative = -3
float_1 = 3.14
float_2 = 6.28
a_sentence = "This is a sentence."
boolean_1 = True
boolean_2 = False

#Addition(int)

print(positive + negative)

#Subtraction(int)

print(positive - negative)

#Addition(float)

print(float_1 + float_2)

#Subtraction(float)

print(float_1 - float_2)

#String slicing

print(a_sentence[10::])

print(f"If true and false then {boolean_1 and boolean_2}")

print(f"If true or false then {boolean_1 or boolean_2}")